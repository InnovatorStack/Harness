import { Database } from "bun:sqlite";

import { prepareBuiltinDatabase } from "../../src/baseline/database.js";
import { auditSourceMaps } from "./sourcemaps.js";
import type { SourceMapEvidence } from "./sourcemaps.js";

const archiveBytesMax = 64 * 1024 * 1024;
const allowedRoots = new Set(["dist", "examples", "skills", "src"]);
const allowedFiles = new Set(["README.md", "LICENSE", "package.json"]);
const privateSegments = new Set([
    "node_modules",
    "workspaces",
    "results",
    "cache",
    "captures",
    "bin",
    "obj",
]);
const confidentialPatterns = [
    /\/(?:home|Users)\/[^/\s"']+\//u,
    /[A-Z]:\\Users\\[^\\\s"']+\\/iu,
    /-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----/u,
    /\bgh[pousr]_[A-Za-z0-9]{36,}\b/u,
    /\bgithub_pat_[A-Za-z0-9_]{40,}\b/u,
];
let expectedBaseline: string | undefined;

/** Check the actual archive, including generated bytes, instead of trusting ignore rules. */
export async function auditDistribution(
    files: ReadonlyMap<string, Blob>,
): Promise<SourceMapEvidence> {
    let bytes = 0;

    for (const [path, file] of files) {
        assertPublicPath(path);
        bytes += file.size;

        if (bytes > archiveBytesMax) {
            throw new Error("The distribution exceeds its 64 MiB review limit.");
        }

        assertPublicText(path, await file.text());
    }

    const baseline = files.get("package/dist/baseline/database.bin");

    if (!baseline) {
        throw new Error("The distribution must contain its generated platform baseline.");
    }

    auditBaseline(new Uint8Array(await baseline.arrayBuffer()));
    await auditExports(files);

    return await auditSourceMaps(files);
}

export function assertPublicText(path: string, text: string): void {
    if (confidentialPatterns.some((pattern) => pattern.test(text))) {
        throw new Error(`Potential confidential content in '${path}'; review locally.`);
    }
}

function assertPublicPath(path: string): void {
    const parts = path.split("/");
    const root = parts[1];

    if (
        parts[0] !== "package" ||
        root === undefined ||
        (!allowedRoots.has(root) && !allowedFiles.has(root)) ||
        parts.some((part) => part === ".." || part === "." || privateSegments.has(part)) ||
        /\.(?:sqlite|tgz|dll|pdb|bak|log)$/iu.test(path) ||
        (root === "src" && !isFrameworkSource(path))
    ) {
        throw new Error(`Unexpected distribution path '${path}'.`);
    }
}

function isFrameworkSource(path: string): boolean {
    return (
        path.endsWith(".ts") ||
        /^package\/src\/baseline\/data\/(?:item-types|properties|records|relationships)\.json$/u.test(
            path,
        )
    );
}

function auditBaseline(bytes: Uint8Array): void {
    expectedBaseline ??= new Bun.CryptoHasher("sha256")
        .update(prepareBuiltinDatabase())
        .digest("hex");
    const actual = new Bun.CryptoHasher("sha256").update(bytes).digest("hex");

    if (actual !== expectedBaseline) {
        throw new Error("The published baseline differs from the curated platform-only build.");
    }

    const database = Database.deserialize(bytes, { strict: true });

    try {
        const documents = database
            .query<{ count: number }, []>("SELECT COUNT(*) AS count FROM _harness_documents")
            .get();
        const methods = database
            .query<{ count: number }, []>(
                "SELECT COUNT(*) AS count FROM _harness_catalog WHERE type IN ('Method', 'SQL')",
            )
            .get();

        if (documents?.count !== 0 || methods?.count !== 0) {
            throw new Error("The built-in baseline must not contain captured documents or code.");
        }

        for (const row of database
            .query<{ source: string }, []>("SELECT source FROM _harness_catalog")
            .all()) {
            const source: unknown = JSON.parse(row.source);

            if (!isRecord(source) || source.file !== "<innovator-harness:baseline-v1>") {
                throw new Error("The built-in baseline contains an external source location.");
            }
        }
    } finally {
        database.close();
    }
}

async function auditExports(files: ReadonlyMap<string, Blob>): Promise<void> {
    const metadata = files.get("package/package.json");
    const value: unknown = metadata ? JSON.parse(await metadata.text()) : undefined;

    if (!isRecord(value) || !isRecord(value.exports)) {
        throw new Error("The distribution must declare its public exports.");
    }

    for (const entry of Object.values(value.exports)) {
        if (!isRecord(entry)) {
            throw new Error("Each public export must declare its types and implementation.");
        }

        for (const target of [entry.types, entry.import]) {
            if (
                typeof target !== "string" ||
                !files.has(`package/${target.replace(/^\.\//u, "")}`)
            ) {
                throw new Error("A public export points outside the distribution.");
            }
        }
    }
}

function isRecord(value: unknown): value is Record<string, unknown> {
    return typeof value === "object" && value !== null && !Array.isArray(value);
}
